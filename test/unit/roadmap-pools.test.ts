import assert from 'node:assert/strict';
import { resolve } from 'node:path';
import { readFileSync } from 'node:fs';
import test from 'node:test';

test('legacy pool controls stay keyboard accessible but are hidden for schema-2 Roadmaps', () => {
    const widget = readFileSync(resolve(import.meta.dirname, '../../packages/theia-extension/src/browser/roadmap-canvas-widget.ts'), 'utf8');
    const css = readFileSync(resolve(import.meta.dirname, '../../packages/theia-extension/src/browser/dope.css'), 'utf8');
    assert.match(widget, /poolFilter\.type = 'search'/);
    assert.match(widget, /aria-label', 'Filter Ideas and Issues'/);
    assert.match(widget, /aria-label', `Promote or link \$\{record\.title\} to selected checkpoint`/);
    assert.match(widget, /aria-label', `Unlink \$\{record\?\.title/);
    assert.match(widget, /link\.type = 'button'/);
    assert.match(widget, /unlink\.type = 'button'/);
    assert.match(widget, /service\.preview\(request\)/);
    assert.match(widget, /service\.apply\(request, preview\.token/);
    assert.match(widget, /this\.stage\.append\(this\.path, this\.status, this\.strategicBar, this\.importEntry, this\.inspection, this\.phaseFocus, this\.poolButton, this\.pools\)/);
    assert.match(widget, /this\.poolButton\.hidden = !!this\.inspector\.gateIndex/);
    assert.match(widget, /if \(this\.inspector\.gateIndex\) \{\s*this\.poolOpen = false;\s*this\.pools\.hidden = true/);
    assert.match(widget, /this\.setPoolOpen\(false\)/);
    assert.match(widget, /this\.pools\.hidden = !open/);
    assert.match(widget, /this\.poolButton\.setAttribute\('aria-expanded', String\(open\)\)/);
    assert.match(widget, /this\.poolFilter\.focus\(\)/);
    assert.match(widget, /this\.poolButton\.focus\(\)/);
    assert.match(widget, /event\.key === 'Escape'.*this\.setPoolOpen\(false\)/);
    const toggle = widget.slice(widget.indexOf('private setPoolOpen('), widget.indexOf('private render(): void'));
    assert.doesNotMatch(toggle, /renderFlow|fitView|schedulePresentation|service\.apply/);
    assert.match(css, /\.dope-roadmap-pools \{ position: absolute; left: 8px; bottom: 48px/);
    assert.match(widget, /Refresh and retry/);
    assert.match(css, /\.dope-roadmap-pools :is\(input, button\):focus-visible/);
    assert.doesNotMatch(widget, /innerHTML|openChatPanel|ChatPanelWidget/);
});
